import type { EvaluationRow } from '../types/evaluation'

function buildRow(
  id: string,
  evaluator: string,
  contact: string,
  title: string,
  date: string,
  venue: string,
  ratings: number[],
  improvement: string,
  suggestions: string,
): EvaluationRow {
  const keys = [
    'relevance_content_job',
    'relevance_topics_needs',
    'materials_organization',
    'examples_practical',
    'knowledge_expertise',
    'responded_queries',
    'evidence_based',
    'theory_practical',
    'presentation_clear',
    'visual_aids',
    'pacing_timing',
    'encouraged_participation',
    'confidence_feedback',
    'courtesy_professionalism',
    'rapport_participants',
    'gained_knowledge',
    'apply_learning',
    'competence_improved',
    'inspired_learning',
    'venue_conducive',
    'av_equipment',
    'schedule_pacing',
    'meals_refreshments',
    'support_staff',
    'overall_satisfaction',
    'recommend_likelihood',
  ] as const

  const ratingRecord = Object.fromEntries(keys.map((key, index) => [key, ratings[index] ?? 3]))

  return {
    id,
    evaluator_name: evaluator,
    training_title: title,
    contact_number: contact,
    venue,
    training_date: date,
    areas_for_improvement: improvement,
    future_suggestions: suggestions,
    ...(ratingRecord as Record<(typeof keys)[number], number>),
  }
}

